function conjugate(verb, formId, kana = false) {
  const source = kana ? verb.reading : verb.word;
  if (formId === 'prohibitive') return source + 'な';
  if (verb.word === '来る') return kuru[formId][kana ? 1 : 0];
  if (verb.group === '不规则' && verb.word.endsWith('する')) return source.slice(0, -2) + suru[formId];
  if (verb.word === 'ある' && formId === 'nai') return 'ない';
  const stem = source.slice(0, -1);
  if (verb.group === '一段') return stem + ichidan[formId];
  const row = rows[source.slice(-1)];
  if (!row) throw new Error(`Unsupported verb ending: ${verb.word}`);
  const ending = {
    masu: row.i + 'ます', nai: row.a + 'ない',
    te: verb.word === '行く' ? 'って' : row.te,
    ta: verb.word === '行く' ? 'った' : row.ta,
    potential: row.e + 'る', volitional: row.o + 'う', conditional: row.e + 'ば',
    passive: row.a + 'れる', causative: row.a + 'せる', imperative: row.e,
    causativePassive: row.a + 'せられる',
  }[formId];
  return stem + ending;
}

function specificRule(verb, formId) {
  if (verb.word === 'ある' && formId === 'nai') return '「ある」的ない形是特殊形式「ない」，不能写成「あらない」。';
  if (verb.word === '行く' && ['te', 'ta'].includes(formId)) return `「行く」虽是く结尾的五段动词，但${formId === 'te' ? 'て形是「行って」' : 'た形是「行った」'}，不用一般的「いて／いた」音变。`;
  if (verb.word === '来る') return `「来る」是不规则动词。这一形式的读音是「${conjugate(verb, formId, true)}」，注意「来」的读音会随形式变化。`;
  if (verb.group === '不规则') return `「${verb.word}」中的「する」按不规则动词变化为「${formId === 'prohibitive' ? 'するな' : suru[formId]}」。${formId === 'potential' ? '可能形用「できる」，不用「しれる」。' : ''}`;
  const irregularRu = ['帰る', '入る', '切る'].includes(verb.word)
    ? `「${verb.word}」是五段动词；不能只看「いる／える」的外形就当成一段。` : '';
  const sameForm = verb.group === '一段' && ['potential', 'passive'].includes(formId)
    ? '一段动词的可能形与被动形外形相同，具体意义要靠句子语境判断。' : '';
  return `「${verb.word}」属于${verb.group}动词。${irregularRu}${sameForm}`;
}

/**
 * Return a typed-answer question, or null for combinations inappropriate for this curriculum.
 * Both the standard written form and its kana reading are accepted. Standard contractions of
 * godan causative-passive forms are also accepted; nonstandard ra-dropped potentials are not.
 */
export function makeVerbQuestion(verb, formId) {
  const form = VERB_FORMS.find(item => item.id === formId);
  if (!form || !VERBS.some(item => item.id === verb?.id)) return null;
  // Existence ある has no ordinary potential/passive/causative; avoid unnatural drills.
  if (verb.word === 'ある' && !['masu', 'nai', 'te', 'ta', 'conditional'].includes(formId)) return null;
  // Do not turn this educational exercise into commands to die or forcing someone to die.
  if (verb.word === '死ぬ' && ['imperative', 'causative', 'causativePassive'].includes(formId)) return null;
  const answer = conjugate(verb, formId);
  const accepted = [answer, conjugate(verb, formId, true)];
  if (formId === 'causativePassive' && verb.group === '五段' && !verb.word.endsWith('す')) {
    accepted.push(answer.replace(/せられる$/, 'される'), conjugate(verb, formId, true).replace(/せられる$/, 'される'));
  }
  if (formId === 'imperative') {
    if (verb.group === '一段') accepted.push(verb.word.slice(0, -1) + 'よ', verb.reading.slice(0, -1) + 'よ');
    if (verb.word.endsWith('する')) accepted.push(verb.word.slice(0, -2) + 'せよ', verb.reading.slice(0, -2) + 'せよ');
  }
  if (formId === 'potential' && verb.word.endsWith('する')) {
    accepted.push(verb.word.slice(0, -2) + '出来る', verb.reading.slice(0, -2) + '出来る');
  }
  return {
    id: `${verb.id}-${formId}`, kind: 'input', subject: 'verb', level: form.level,
    prompt: `将「${verb.word}」变为${form.label}`, context: `${verb.reading} · ${verb.meaning} · ${verb.group}动词`,
    answer, accepted: [...new Set(accepted)],
    explanation: `${specificRule(verb, formId)} ${form.rule} 「${verb.word}」→「${answer}」。`,
    point: form.label,
  };
}
